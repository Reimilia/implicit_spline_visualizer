import { createRequire } from 'node:module';
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// Run with the path to an unpacked KaTeX npm package directory.
const packageDirectory = process.argv[2];
if (!packageDirectory) {
  throw new Error('Usage: node scripts/build_algorithm_math.mjs PATH_TO_KATEX_PACKAGE');
}
const katexRoot = pathToFileURL(resolve(packageDirectory) + '/');
const require = createRequire(import.meta.url);
const katex = require(resolve(packageDirectory, 'dist/katex.js'));
if (katex.version !== '0.19.1') {
  throw new Error('Use the pinned KaTeX 0.19.1 package.');
}

const site = new URL('../web_demo/', import.meta.url);
const source = JSON.parse(await readFile(new URL('algorithm_math.json', import.meta.url), 'utf8'));
const rendered = Object.fromEntries(Object.entries(source).map(([key, { tex, display = false }]) => [
  key,
  katex.renderToString(tex, { displayMode: display, output: 'htmlAndMathml', throwOnError: true, strict: 'error' })
]));
await writeFile(new URL('equations.js', site),
  '// Generated by scripts/build_algorithm_math.mjs from algorithm_math.json.\nexport const MATH = ' +
  JSON.stringify(rendered, null, 2) + ';\n');

const vendor = new URL('assets/katex/', site);
await mkdir(new URL('fonts/', vendor), { recursive: true });
const css = await readFile(new URL('dist/katex.min.css', katexRoot), 'utf8');
// Keep the WOFF2 source for each face. All target browsers support WOFF2.
const woff2Css = css.replace(/,url\([^)]*\.(?:woff|ttf)\) format\([^)]+\)/g, '');
await writeFile(new URL('katex.min.css', vendor), woff2Css);
const fonts = new URL('dist/fonts/', katexRoot);
for (const name of await readdir(fonts)) {
  if (name.endsWith('.woff2')) await copyFile(new URL(name, fonts), new URL('fonts/' + name, vendor));
}
await copyFile(new URL('LICENSE', katexRoot), new URL('LICENSE', vendor));
